-- ---- points trigger (ported; pinned to the passport schema) -------------
-- On each scan: apply the activity's x2 marketing bonus and add the km to the
-- user's profile total. SECURITY DEFINER + an explicit search_path so the
-- unqualified table names resolve to passport.* (and can't be hijacked).
create or replace function passport.handle_new_scan()
returns trigger
language plpgsql
security definer
set search_path = passport
as $$
declare
  calculated_points integer;
  act_marketing_bonus boolean;
begin
  select is_marketing_bonus into act_marketing_bonus from activities where id = new.activity_id;
  calculated_points := new.points_awarded;
  if act_marketing_bonus then
    calculated_points := calculated_points * 2;
  end if;
  new.points_awarded := calculated_points;
  update profiles set total_km = total_km + calculated_points where id = new.user_id;
  return new;
end;
$$;

drop trigger if exists on_new_scan on passport.scans;
create trigger on_new_scan before insert on passport.scans
  for each row execute function passport.handle_new_scan();

-- handle_new_user() is ported for completeness but DELIBERATELY NOT attached
-- to auth.users here. In project A, auth.users already carries samoweb's own
-- signup triggers; adding a passport trigger that fires on EVERY signup (incl.
-- non-passport staff) — and could fail — risks bricking samoweb signups, the
-- exact 0041 failure class. Passport profiles are created by the Phase 1 data
-- copy; new post-cutover students are handled by a guarded mechanism decided
-- at cutover (app-side upsert on login, or a domain-gated trigger). Kept here
-- schema-pinned so that decision has the function ready.
create or replace function passport.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = passport
as $$
begin
  insert into passport.profiles (id, email, full_name, total_km)
  values (new.id, new.email, new.raw_user_meta_data->>'full_name', 0);
  return new;
end;
$$;

-- ---- tier view ----------------------------------------------------------
create or replace view passport.user_tiers as
  select p.id, p.full_name, p.total_km, p.tier_override,
    case
      when p.tier_override is not null then p.tier_override
      when p.total_km >= 7500 then 'The Ambassador'
      when p.total_km >= 2500 then 'The Voyager'
      when p.total_km >= 1000 then 'The Explorer'
      else 'Novice Traveler'
    end as final_tier,
    ((select count(*) from passport.scans s
       where s.user_id = p.id and s.scanned_at > (now() - interval '30 days')) >= 3) as has_travel_visa
  from passport.profiles p;

-- ---- RLS (permissive model ported verbatim from B) ----------------------
-- Passport uses the anon key with `using(true)` policies (its own STATE.md
-- documents this as intentional). `profiles` is the exception: public read,
-- own-row update only. departments / sub_departments have RLS ENABLED with NO
-- policy in B (⇒ not anon-readable) — replicated faithfully; the app doesn't
-- read them over the anon key. Tighten later if passport gets real admin auth.
alter table passport.activities      enable row level security;
alter table passport.certificates    enable row level security;
alter table passport.departments     enable row level security;
alter table passport.sub_departments enable row level security;
alter table passport.profiles        enable row level security;
alter table passport.samo_seasons    enable row level security;
alter table passport.samo_years      enable row level security;
alter table passport.scans           enable row level security;
alter table passport.season_results  enable row level security;
alter table passport.seasons         enable row level security;

do $$
declare t text;
begin
  -- full CRUD-open policies for the admin-model tables
  foreach t in array array['activities','certificates','samo_seasons','samo_years','scans','seasons'] loop
    execute format('drop policy if exists %I on passport.%I', t||'_read',   t);
    execute format('drop policy if exists %I on passport.%I', t||'_insert', t);
    execute format('drop policy if exists %I on passport.%I', t||'_update', t);
    execute format('drop policy if exists %I on passport.%I', t||'_delete', t);
    execute format('create policy %I on passport.%I for select using (true)',            t||'_read',   t);
    execute format('create policy %I on passport.%I for insert with check (true)',        t||'_insert', t);
    execute format('create policy %I on passport.%I for update using (true) with check (true)', t||'_update', t);
    execute format('create policy %I on passport.%I for delete using (true)',             t||'_delete', t);
  end loop;
end $$;

-- season_results: read/insert/delete open, no update (matches B)
drop policy if exists season_results_read   on passport.season_results;
drop policy if exists season_results_insert on passport.season_results;
drop policy if exists season_results_delete on passport.season_results;
create policy season_results_read   on passport.season_results for select using (true);
create policy season_results_insert on passport.season_results for insert with check (true);
create policy season_results_delete on passport.season_results for delete using (true);

-- profiles: public read, own-row update
drop policy if exists profiles_read_all   on passport.profiles;
drop policy if exists profiles_update_own on passport.profiles;
create policy profiles_read_all   on passport.profiles for select using (true);
create policy profiles_update_own on passport.profiles for update using (auth.uid() = id) with check (auth.uid() = id);


-- ============================================================
-- 0056 — passport schema: isolated home for Samo Passport inside samoweb's
--        Supabase project (A = fheueuowbchsnsvbcgil), for the shared-login
--        merge. See docs/PASSPORT-MERGE.md.
--
-- WHAT: a faithful port of the live Samo Passport database (project B =
--   idwlabpbwiwgaoqwbozz) — generated from `pg_dump --schema-only` of B on
--   2026-07-21 — re-homed under a dedicated `passport` schema instead of
--   `public`.
--
-- WHY a separate schema: it is a structural firewall. Everything passport
--   owns is `passport.*`; a passport migration can NEVER touch
--   `public.pr_tickets` / `public.users` etc. Creating this schema does not
--   read or write anything in `public`, so applying it CANNOT affect
--   samoweb. Fully reversible: `drop schema passport cascade`.
--
-- SCOPE = Phase 0 (schema only). NO data (that's Phase 1, email re-keyed) and
--   deliberately NO trigger on `auth.users` (see the handle_new_user note
--   below) — so this is isolated to the new schema and safe on production.
--
-- TWO MANUAL STEPS AFTER APPLYING (nothing works from the app without them):
--   1. Supabase → Settings → API → "Exposed schemas" → add `passport`
--      (PostgREST won't serve passport.* over the anon key otherwise).
--   2. Point the passport app's supabase client at this schema, e.g.
--      createClient(url, key, { db: { schema: 'passport' } }) — a passport
--      CODE change made at cutover (Phase 3), not now.
-- ============================================================


// ==============================================
// dev-activity.js — the "เบื้องหลังการพัฒนา" panel on the landing page.
//
// WHAT THIS PANEL DELIBERATELY DOES NOT SHOW, AND WHY
// The first version of this panel showed commits, active days, lines added and
// deleted, a longest-streak counter and a GitHub-style commit heatmap. All of it
// was real and all of it was the wrong thing to show:
//
//   • Commit count and lines-of-code are discredited as measures of work even
//     INSIDE engineering — more code is a cost to maintain, not an achievement,
//     and commit counts reward splitting work rather than doing it.
//   • The audience here is SAMO members, not developers. "549 ครั้งที่ส่งงานเข้า
//     ระบบ" is not a sentence a reader can judge. They cannot tell whether it is
//     a lot, and nothing in it says what they got.
//   • A dense heatmap of nights and weekends reads as grinding, not competence.
//     It invites "so you were busy — and?"
//
// So the panel now measures OUTCOME: which systems exist that did not exist
// before, how long that took, how often it keeps improving, and who built it.
// Every number here is something a non-technical reader can weigh. The raw
// history still lives in src/data/dev-activity.json (regenerated by
// `npm run gen:activity`) — this file reads only the date range and the
// contributor list from it.
// ==============================================

import activity from '../data/dev-activity.json';
import { RELEASES, SYSTEMS, LATEST } from '../data/changelog.js';
import { escHtml } from './utils.js';

const THAI_MONTHS_SHORT = ['ม.ค.', 'ก.พ.', 'มี.ค.', 'เม.ย.', 'พ.ค.', 'มิ.ย.', 'ก.ค.', 'ส.ค.', 'ก.ย.', 'ต.ค.', 'พ.ย.', 'ธ.ค.'];

const shortDate = (iso) => {
  const [, m, d] = String(iso).split('-').map(Number);
  return `${d} ${THAI_MONTHS_SHORT[m - 1]}`;
};

/** Whole weeks between the first and last day of the build. */
export function weeksBetween(firstIso, lastIso) {
  const ms = new Date(`${lastIso}T00:00:00Z`) - new Date(`${firstIso}T00:00:00Z`);
  return Math.max(1, Math.round(ms / (7 * 86400000)));
}

/** Mean days between releases — "how often does this thing actually improve". */
export function releaseCadenceDays(releases) {
  if (releases.length < 2) return 0;
  const dates = releases.map((r) => new Date(`${r.date}T00:00:00Z`).getTime());
  const span = Math.max(...dates) - Math.min(...dates);
  return Math.max(1, Math.round(span / 86400000 / (releases.length - 1)));
}

function easeOutCubic(t) { return 1 - (1 - t) ** 3; }

function countUp(el, target, suffix = '') {
  const dur = 1100;
  const start = performance.now();
  const step = (now) => {
    const t = Math.min((now - start) / dur, 1);
    el.textContent = Math.round(target * easeOutCubic(t)).toLocaleString('en-US') + suffix;
    if (t < 1) requestAnimationFrame(step);
    else el.textContent = target.toLocaleString('en-US') + suffix;
  };
  requestAnimationFrame(step);
}

function tile(icon, value, suffix, label, sub) {
  return `
    <div class="devact-tile">
      <span class="devact-tile-icon"><i class="bi ${icon}" aria-hidden="true"></i></span>
      <span class="devact-tile-num" data-count="${Number(value) || 0}" data-suffix="${escHtml(suffix)}">0${escHtml(suffix)}</span>
      <span class="devact-tile-label">${escHtml(label)}</span>
      ${sub ? `<span class="devact-tile-sub">${escHtml(sub)}</span>` : ''}
    </div>`;
}

/**
 * The launch timeline.
 *
 * Steps are EVENLY SPACED, not positioned proportionally to their dates. Two
 * systems launched on the same day (ร้านค้า and หนังสือโครงการ, 26 พ.ค.) and a
 * proportional axis would draw them on top of each other; every step also
 * carries its real date, so nothing is hidden by the even spacing. What the
 * reader is meant to take from this is the sequence and the pace, and the dates
 * supply the rest.
 */
function timelineHtml() {
  const steps = SYSTEMS.map((s, i) => `
    <li class="devact-step" style="--i:${i}">
      <span class="devact-step-node" aria-hidden="true"><i class="bi ${s.icon}"></i></span>
      <span class="devact-step-body">
        <span class="devact-step-date">${escHtml(shortDate(s.date))}</span>
        <span class="devact-step-name">${escHtml(s.label)}</span>
        <span class="devact-step-note">${escHtml(s.note)}</span>
      </span>
    </li>`).join('');

  return `
    <section class="devact-timeline" aria-label="ลำดับการเปิดใช้งานของแต่ละระบบ">
      <h3 class="devact-timeline-title">
        <i class="bi bi-signpost-split" aria-hidden="true"></i>
        ลำดับการเปิดใช้งานระบบ
      </h3>
      <ol class="devact-track">${steps}</ol>
    </section>`;
}

function render(host) {
  const weeks = weeksBetween(activity.range.first, activity.range.last);
  const cadence = releaseCadenceDays(RELEASES);
  const from = THAI_MONTHS_SHORT[Number(activity.range.first.slice(5, 7)) - 1];
  const to = THAI_MONTHS_SHORT[Number(activity.range.last.slice(5, 7)) - 1];
  const year = Number(activity.range.first.slice(0, 4)) + 543;

  host.innerHTML = `
    <div class="devact-inner">
      <div class="devact-glow" aria-hidden="true"></div>

      <header class="devact-head">
        <span class="devact-eyebrow"><i class="bi bi-tools" aria-hidden="true"></i> เบื้องหลังการพัฒนา</span>
        <h2 id="devactHeading">พัฒนาและดูแลระบบอย่างต่อเนื่อง</h2>
        <p>
          IT SAMO'69 ดูแลและพัฒนา SAMO Portal ทั้งระบบ ตั้งแต่ฟอร์ม PR,
          VitalSound, ร้านค้า, หนังสือโครงการ ไปจนถึง SAMO Passport
          — ปัจจุบันเวอร์ชัน ${escHtml(LATEST.version)} อัปเดตล่าสุด ${escHtml(shortDate(LATEST.date))} ${year}
        </p>
      </header>

      <div class="devact-tiles">
        ${tile('bi-boxes', SYSTEMS.length, '', 'ระบบที่เปิดใช้งาน', 'เปิดให้ใช้งานจริงทั้งหมด')}
        ${tile('bi-tag', RELEASES.length, '', 'เวอร์ชันที่เผยแพร่', `เฉลี่ยทุก ${cadence} วัน`)}
        ${tile('bi-calendar3-range', weeks, '', 'สัปดาห์ของการพัฒนา', `${from} – ${to} ${year}`)}
      </div>

      ${timelineHtml()}

      <footer class="devact-foot">
        <p class="devact-credit">
          <i class="bi bi-people-fill" aria-hidden="true"></i>
          ดูแลโดย IT SAMO'69
        </p>
        <a class="devact-cta" href="/updates"
           onclick="event.preventDefault(); window.openUpdates && window.openUpdates();">
          ดูอัปเดตทั้งหมด <i class="bi bi-arrow-right" aria-hidden="true"></i>
        </a>
      </footer>
    </div>`;

  const inner = host.querySelector('.devact-inner');
  const run = () => {
    if (inner.dataset.ran) return;
    inner.dataset.ran = '1';
    inner.classList.add('is-in');
    host.querySelectorAll('[data-count]').forEach((el) => {
      countUp(el, Number(el.dataset.count || 0), el.dataset.suffix || '');
    });
  };
  if ('IntersectionObserver' in window) {
    const io = new IntersectionObserver((es) => {
      es.forEach((e) => { if (e.isIntersecting) { run(); io.disconnect(); } });
    }, { threshold: 0.15 });
    io.observe(inner);
  } else { run(); }
  // A deep link to another tab leaves home hidden, so the observer may never
  // fire. run() is idempotent.
  document.addEventListener('shown.bs.tab', (e) => {
    if (e.target?.id === 'pills-home-tab') run();
  });
}

export function initDevActivity() {
  const host = document.getElementById('devActivity');
  if (!host || host.dataset.done) return;
  host.dataset.done = '1';
  render(host);
  host.classList.remove('d-none');
}
